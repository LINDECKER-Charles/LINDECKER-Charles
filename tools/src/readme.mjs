/**
 * Le README, écrit à partir du même contenu que les visuels : chaque image a
 * son texte de remplacement, chaque bouton son lien. Les panneaux passent en
 * version téléphone sous 700 px de large (`<picture>`).
 */
import { LINKS, PROJECT_PAGES } from './content.mjs';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

export function readme(t, { assets = './assets', mobileBase } = {}) {
  const lang = t.lang;
  const src = (name, ext = 'svg') => `${assets}/${lang}/${name}.${ext}`;
  const set = (name, ext = 'svg') => `${mobileBase ?? assets}/${lang}/${name}.${ext}`;
  const fr = lang === 'fr';
  const P = t.projects;

  /** Un panneau pleine largeur, sa version téléphone et son lien éventuel. */
  const pic = (name, alt, link, ext = 'svg') => {
    const img = `<img src="${src(name, ext)}" width="100%" alt="${esc(alt)}">`;
    const inner = `<picture><source media="(max-width: 700px)" srcset="${set(`${name}.mobile`, ext)}">${img}</picture>`;
    return `<p align="center">\n  ${link ? `<a href="${link}">${inner}</a>` : inner}\n</p>`;
  };
  /** Une rangée de boutons. */
  const row = (items) =>
    `<p align="center">\n${items.map(([id, href, alt]) => `  <a href="${href}"><img src="${src(`btn-${id}`)}" height="46" alt="${esc(alt)}"></a>`).join('&nbsp;\n')}\n</p>`;
  const b = t.buttons;
  const blr = fr ? LINKS.blr : LINKS.blrEn;
  const journal = fr ? LINKS.blrJournal : LINKS.blrJournalEn;
  const league = fr ? LINKS.league : LINKS.leagueEn;
  const page = (slug) => PROJECT_PAGES(slug);

  const parts = [
    `<!-- ${fr ? 'Généré par tools/build.mjs : modifier tools/src/content.mjs, puis « npm run build » dans tools/.' : 'Generated by tools/build.mjs: edit tools/src/content.mjs, then run “npm run build” in tools/.'} -->`,
    row([['lang', t.other.href, t.other.label]]).replace('<p align="center">', '<p align="right">'),
    pic('hero', t.hero.alt, LINKS.portfolio),
    row([
      ['portfolio', LINKS.portfolio, b.portfolio],
      ['linkedin', LINKS.linkedin, b.linkedin],
      ['email', LINKS.email, `${b.email} : ${LINKS.emailText}`],
    ]),
    pic('hunter', t.hunter.alt, LINKS.linkedin),
    pic('rules', t.rules.alt, page('')),
    pic('sky', t.sky.alt, page('projets')),
    pic('flagship', t.flagship.alt, blr),
    pic('rituals', t.rituals.alt, blr, 'webp'),
    row([
      ['app', blr, `${b.app} — Bloodborne Legendary Run`],
      ['journal', journal, `${b.journal} — Bloodborne Legendary Run`],
    ]),
    pic('sep-equipe', t.sky.families.equipe),
    pic('card-pvz', `${P.pvz.name} — ${P.pvz.proof}. ${P.pvz.title.join(' ')} ${P.pvz.need} ${P.pvz.figures.map((f) => `${f.v} ${f.l}`).join(' ; ')}.`, LINKS.pvzUpstream),
    row([
      ['upstream', LINKS.pvzUpstream, `${b.upstream} — PvZ Fusion`],
      ['tool', LINKS.consoleManager, `${b.tool} — Console Manager`],
    ]),
    pic('sep-jeu', t.sky.families.jeu),
    pic('card-omnicard', cardAlt(P.omnicard), LINKS.omnicardRules),
    row([['rules', LINKS.omnicardRules, `${b.rules} — Omnicard`]]),
    pic('card-league', cardAlt(P.league), league),
    row([
      ['app', league, `${b.app} — League Of Data Base`],
      ['code', LINKS.leagueCode, `${b.code} — League Of Data Base`],
    ]),
    pic('sep-outils', t.sky.families.outils),
    pic('card-gup', cardAlt(P.gup), LINKS.gup),
    row([
      ['code', LINKS.gup, `${b.code} — gup`],
      ['npm', LINKS.gupNpm, 'npm — gup'],
      ['site', LINKS.gupSite, `${b.site} — gup`],
    ]),
    pic('card-githealth', cardAlt(P.githealth), LINKS.githealth),
    row([['code', LINKS.githealth, `${b.code} — GitHealth`]]),
    pic('sep-ia', t.sky.families.ia),
    pic('card-karl', `${cardAlt(P.karl)} ${P.privateNote}.`, page('projets/karl-scraper')),
    pic('card-sillage', `${cardAlt(P.sillage)} ${P.privateNote}.`, page('projets/sillage')),
    pic('card-relais', `${cardAlt(P.relais)} ${P.privateNote}.`, page('projets/relais')),
    pic('note-releve', P.releve),
    pic('path', t.path.alt, LINKS.linkedin),
    pic('arsenal', t.arsenal.alt, LINKS.repos),
    pic('grimoire', t.grimoire.alt, LINKS.freecodecamp),
    row([
      ['certs', LINKS.freecodecamp, `${b.certs} — freeCodeCamp`],
      ['fm', LINKS.frontendMentor, b.fm],
    ]),
    pic('end', t.end.alt, LINKS.email),
    row([
      ['talk', LINKS.email, `${b.talk} : ${LINKS.emailText}`],
      ['linkedin', LINKS.linkedin, b.linkedin],
      ['portfolio', LINKS.portfolio, b.portfolio],
    ]),
    row([
      ['contribGup', LINKS.gupContrib, `${b.contrib} — gup`],
      ['contribConsole', LINKS.consoleManagerContrib, `${b.contrib} — Console Manager`],
    ]),
    pic('footer', t.end.footAlt, LINKS.portfolio),
    pic('note-credits', t.credits),
  ];
  return parts.join('\n\n') + '\n';
}

function cardAlt(P) {
  return `${P.name} (${P.family}) — ${P.proof}. ${P.need} ${P.figure.v} ${P.figure.l}. ${P.role}. ${P.status}.`;
}
